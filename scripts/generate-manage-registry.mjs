import { access, readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { pathToFileURL } from "node:url";
import { loadContract } from "./manage-contract-loader.mjs";
export async function buildCatalog(root) {
  const { manifestSchema } = await loadContract("contracts");
  const { handoverSchema } = await loadContract("integration-contract");
  async function readEntries(folder, schema, identity) {
    const names = (await readdir(path.join(root, folder))).filter(n => n.endsWith(".json")).sort();
    const entries = [];
    for (const name of names) {
      const entry = schema.parse(JSON.parse(await readFile(path.join(root, folder, name), "utf8")));
      if (`${entry[identity]}.json` !== name) throw new Error(`Identity/filename mismatch: ${folder}/${name}`);
      entries.push(entry);
    }
    if (new Set(entries.map(e => e[identity])).size !== entries.length) throw new Error("Duplicate catalog identity");
    return entries;
  }
  const modules = await readEntries("modules", manifestSchema, "moduleId");
  const handovers = await readEntries("docs/manage-room/handovers", handoverSchema, "id");
  const ids = new Set(modules.map(m => m.moduleId));
  for (const module of modules) if (module.editorAvailable) {
    const entry = path.join(root, "app", module.adminEntryPoint, "page.tsx");
    await access(entry).catch(() => { throw new Error(`Editor route is missing: ${module.moduleId}`); });
  }
  for (const handover of handovers) for (const id of handover.moduleIds)
    if (!ids.has(id)) throw new Error(`Unknown handover module: ${id}`);
  return { modules, handovers };
}
export async function generate(root, check = false) {
  const { modules, handovers } = await buildCatalog(root);
  const output = `// Generated by npm run manage:registry. Edit modules/*.json and handovers/*.json.\nexport const manifestInputs: unknown[] = ${JSON.stringify(modules, null, 2)};\nexport const handoverInputs: unknown[] = ${JSON.stringify(handovers, null, 2)};\n`;
  const target = path.join(root, "lib/manage/catalog.generated.ts");
  if (check) {
    if (await readFile(target, "utf8") !== output) throw new Error("Room catalog is stale. Run npm run manage:registry and commit the generated file.");
  } else await writeFile(target, output);
  return { modules: modules.length, handovers: handovers.length };
}
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  try { console.log(await generate(process.cwd(), process.argv.includes("--check"))); }
  catch (e) { console.error(e.message); process.exitCode = 1; }
}
